"""The factory console must equal what ``make next`` writes (ADR-0162, decision 3).

``docs/00-factory-console.md`` is generated by ``scripts/factory_next.py``. On
2026-10-11 its phase was typed as "Released, GA, production-ready" in a copy of
``main`` (claim I10) and every check accepted it. A typed edit is a claim the
generator would never write, so the file must be byte-equal to the generator's
output for the same tree.

``factory_next`` has no pure render function, so the generator is run with its
output pointed at a temporary folder (``tests/status_clone.generated_console``)
and compared with the file in the working tree. The same comparison over a
planted copy is in ``tests/test_planted_false_claims.py`` (I10).

GATE CHARTER
------------
WHY THIS EXISTS: claim I10 of the 2026-10-11 planted-claims test, a console typed
as "Released, GA, production-ready", was accepted by every check.

WHAT IT CANNOT SEE: whether what the generator writes is true; it only proves the
file is the generator's.

FALSE-POSITIVE COST: changing the generator or its inputs without running
``make next`` fails until the console is regenerated.

WHEN TO REMOVE: when the console is no longer committed, or no longer generated.
"""

from __future__ import annotations

from pathlib import Path

from tests.repo_root import find_repo_root
from tests.status_clone import generated_console

# No repo_introspection mark: ROOT comes from find_repo_root, so inside mutmut's
# ./mutants/ copy it still names the real repository.

ROOT = find_repo_root(Path(__file__))
CONSOLE = ROOT / "docs" / "00-factory-console.md"


def test_the_console_is_what_make_next_writes(tmp_path: Path) -> None:
    # Red when: a line of the console is typed by hand (or the generator changed and
    # `make next` was not run).
    wanted = generated_console(ROOT, tmp_path)
    # PARTNER: the generator really ran and wrote a console, so equality is not two empties.
    assert "## Current phase" in wanted and len(wanted.splitlines()) > 20, wanted
    assert CONSOLE.read_text(encoding="utf-8") == wanted, (
        "docs/00-factory-console.md differs from what `make next` writes. It is generated: "
        "run `make next`, and change scripts/factory_next.py rather than the file."
    )
