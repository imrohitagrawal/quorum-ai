"""W68: ``scripts/vuln_audit.py`` audits the LOCKED runtime libraries with
``pip-audit`` and fails CI on a known vulnerability (finding S3 of
``docs/analysis/2026-10-13-security-review.md``: anyio 4.14.0 and urllib3
2.7.0 carried six, and nothing in CI looked).

Every subprocess goes through the injected ``run`` argument, so these tests
make no network call and need neither ``uv`` nor ``pip-audit``: a fake records
each command line and returns canned results.

The gate must report what it counted and refuse to pass on an empty input
(AGENTS.md, "Every gate must report what it counted"): an empty export, an
unparsable report and a report listing no dependencies all exit 2.

WHAT TURNS THIS FILE RED: make ``main`` return 0 when pip-audit lists a
vulnerability, or call pip-audit (or pass) when the export is empty.
"""

