def test_pip_audit_command_is_pinned_and_audits_only_the_listed_file(
    capsys: pytest.CaptureFixture[str],
) -> None:
    """Red when: pip-audit is not run through ``uvx --from
    pip-audit==2.10.1`` (an unpinned tool changes under the gate), or lacks
    ``-r <file>``, ``--no-deps`` (the export is already the full locked set;
    resolving again could audit other versions), ``--disable-pip`` or
    ``--format json``."""
    fake = _FakeRun(_Done(0, _EXPORT_3), _audit(_clean_deps()))
    _module().main([], run=fake)
    capsys.readouterr()
    calls = fake.tool_calls("uvx")
    assert len(calls) == 1, fake.calls
    argv = calls[0]
    assert argv[argv.index("--from") + 1] == "pip-audit==2.10.1", argv
    assert "pip-audit" in argv[argv.index("--from") + 2 :], argv
    assert "-r" in argv, argv
    assert "--no-deps" in argv and "--disable-pip" in argv, argv
    assert argv[argv.index("--format") + 1] == "json", argv
