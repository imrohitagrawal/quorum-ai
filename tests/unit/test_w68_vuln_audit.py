def test_count_pinned_counts_exactly_the_pinned_lines_of_a_real_export() -> None:
    """Red when: ``count_pinned`` counts comment, ``# via``, option, ``-e``
    or blank lines (the sample has 8 pins among 26 lines), or drops a line
    because it carries an environment marker (3 of the 8 do)."""
    assert _module().count_pinned(_REAL_EXPORT_SAMPLE) == 8


def test_count_pinned_is_zero_for_the_header_only() -> None:
    """Red when: ``count_pinned`` counts the generated header's comment lines,
    so an empty export would look like a non-empty one and the refusal below
    could never fire. Partner: the test above, where the count is 8."""
    assert _module().count_pinned(_EXPORT_EMPTY) == 0


def test_locked_runtime_requirements_exports_the_frozen_runtime_set() -> None:
    """Red when: the export is not ``uv export`` with ``--frozen`` (read the
    lock, never re-resolve), ``--no-dev``, ``--no-emit-project`` and
    ``--no-hashes``, or the function does not return that command's stdout."""
    fake = _FakeRun(_Done(0, _EXPORT_3))
    assert _module().locked_runtime_requirements(run=fake) == _EXPORT_3
    assert len(fake.calls) == 1
    argv = fake.calls[0]
    assert Path(argv[0]).name == "uv" and argv[1] == "export", argv
    for flag in ("--frozen", "--no-dev", "--no-emit-project", "--no-hashes"):
        assert flag in argv, (flag, argv)


