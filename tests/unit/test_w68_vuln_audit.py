def _module() -> ModuleType:
    assert _SCRIPT.is_file(), f"{_SCRIPT} does not exist"
    spec = importlib.util.spec_from_file_location("vuln_audit_under_test", _SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@dataclass
class _Done:
    returncode: int
    stdout: str
    stderr: str = ""


class _FakeRun:
    """Stands in for ``subprocess.run``: ``uv`` gets the export, ``uvx`` gets
    the pip-audit result. Records every argv, and the requirements file's
    content at the moment pip-audit is called."""

    def __init__(self, export: _Done, audit: _Done | None = None) -> None:
        self.export = export
        self.audit = audit
        self.calls: list[list[str]] = []
        self.audited_text: str | None = None

    def __call__(self, command: Sequence[object], **_kwargs: object) -> _Done:
        argv = [str(a) for a in command]
        self.calls.append(argv)
        tool = Path(argv[0]).name
        if tool == "uv":
            return self.export
        if tool == "uvx":
            self.audited_text = Path(argv[argv.index("-r") + 1]).read_text(encoding="utf-8")
            assert self.audit is not None, "pip-audit was called but the test gave it no result"
            return self.audit
        raise AssertionError(f"unexpected command: {argv}")

    def tool_calls(self, tool: str) -> list[list[str]]:
        return [c for c in self.calls if Path(c[0]).name == tool]


def _audit(deps: list[dict[str, Any]], returncode: int = 0) -> _Done:
    return _Done(returncode, json.dumps({"dependencies": deps, "fixes": []}))


def _clean_deps() -> list[dict[str, Any]]:
    return [
        {"name": "anyio", "version": "4.14.0", "vulns": []},
        {"name": "certifi", "version": "2026.6.17", "vulns": []},
        {"name": "urllib3", "version": "2.7.0", "vulns": []},
    ]


def _vuln_deps() -> list[dict[str, Any]]:
    return [
        {
            "name": "anyio",
            "version": "4.14.0",
            "vulns": [
                {"id": "PYSEC-2026-4023", "fix_versions": ["4.14.2"], "aliases": []},
                {"id": "PYSEC-2026-4024", "fix_versions": ["4.14.2"], "aliases": []},
            ],
        },
        {"name": "certifi", "version": "2026.6.17", "vulns": []},
        {
            "name": "urllib3",
            "version": "2.7.0",
            "vulns": [{"id": "PYSEC-2026-4175", "fix_versions": ["2.8.0"], "aliases": []}],
        },
    ]


def _lines(capsys: pytest.CaptureFixture[str]) -> tuple[list[str], str]:
    captured = capsys.readouterr()
    return captured.out.splitlines(), captured.out + captured.err


def _summary(lines: list[str]) -> tuple[int, int]:
    pattern = re.compile(r"vuln-audit: (\d+) packages, (\d+) known vulnerabilities")
    found = [m for line in lines if (m := pattern.fullmatch(line.strip()))]
    assert len(found) == 1, lines
    return int(found[0].group(1)), int(found[0].group(2))


