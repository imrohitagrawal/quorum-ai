def test_main_reads_the_named_image_with_the_venv_python(
    capsys: pytest.CaptureFixture[str],
) -> None:
    """Red when: the docker command is not ``docker run --rm --entrypoint
    /opt/venv/bin/python <image> -c <snippet>`` for the image named by
    ``--image`` (the image's own entrypoint is uvicorn; the venv's python is
    what lists the shipped packages), or the lock is not read with ``uv
    export --frozen --no-dev --no-emit-project --no-hashes``."""
    fake = _FakeRun(_Done(0, _LOCKED), _Done(0, _INSTALLED_SAME))
    _module().main(["--image", "quorum-ai:test-tag"], run=fake)
    capsys.readouterr()
    docker = fake.tool_calls("docker")
    assert len(docker) == 1, fake.calls
    argv = docker[0]
    assert argv[1] == "run" and "--rm" in argv, argv
    assert argv[argv.index("--entrypoint") + 1] == "/opt/venv/bin/python", argv
    assert "quorum-ai:test-tag" in argv, argv
    assert argv.index("-c") > argv.index("quorum-ai:test-tag"), argv
    uv = fake.tool_calls("uv")
    assert len(uv) == 1, fake.calls
    assert uv[0][1] == "export", uv[0]
    for flag in ("--frozen", "--no-dev", "--no-emit-project", "--no-hashes"):
        assert flag in uv[0], (flag, uv[0])


