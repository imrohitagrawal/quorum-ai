def test_compare_identical_is_empty() -> None:
    """Partner, for the three tests below: identical sides give ``[]``. Red
    when: ``compare`` reports a difference where there is none."""
    pins = {"anyio": "4.14.0", "urllib3": "2.7.0"}
    assert _module().compare(dict(pins), dict(pins)) == []


def test_compare_reports_a_missing_package() -> None:
    """Red when: a package the lock pins but the image lacks is not reported
    (exactly one difference, naming it and its locked version)."""
    diffs = _module().compare({"anyio": "4.14.0", "pycparser": "3.11"}, {"anyio": "4.14.0"})
    assert len(diffs) == 1, diffs
    assert "pycparser" in diffs[0] and "3.11" in diffs[0], diffs


def test_compare_reports_an_extra_package() -> None:
    """Red when: a package installed in the image but not in the lock is not
    reported (exactly one difference, naming it)."""
    diffs = _module().compare({"anyio": "4.14.0"}, {"anyio": "4.14.0", "rogue-package": "9.9"})
    assert len(diffs) == 1, diffs
    assert "rogue-package" in diffs[0], diffs


def test_compare_reports_a_version_difference() -> None:
    """Red when: the same package at a different version is not reported
    (exactly one difference, carrying both versions). This is S4's case:
    the lock said 4.14.0, the image had 4.15.1."""
    diffs = _module().compare({"anyio": "4.14.0"}, {"anyio": "4.15.1"})
    assert len(diffs) == 1, diffs
    assert "anyio" in diffs[0] and "4.14.0" in diffs[0] and "4.15.1" in diffs[0], diffs


def test_compare_counts_every_difference() -> None:
    """Red when: ``compare`` stops at the first difference or merges them:
    two missing, one extra and one version change are four differences."""
    locked = {"a-one": "1", "b-two": "2", "c-three": "3", "same": "1.0"}
    installed = {"c-three": "3.1", "d-four": "4", "same": "1.0"}
    assert len(_module().compare(locked, installed)) == 4


def test_compare_ignores_only_pip_setuptools_and_wheel_as_extras() -> None:
    """Red when: ``pip``, ``setuptools`` or ``wheel`` present in the image but
    not the lock is reported (they are installer tooling, not runtime
    libraries), or when that allowance leaks to other names: ``pipx`` and
    ``wheel-extra`` installed but not locked must still be reported."""
    mod = _module()
    locked = {"anyio": "4.14.0"}
    tooling = {"anyio": "4.14.0", "pip": "25.2", "setuptools": "80.9.0", "wheel": "0.45.1"}
    assert mod.compare(locked, tooling) == []
    lookalikes = {"anyio": "4.14.0", "pipx": "1.7.1", "wheel-extra": "1.0"}
    assert len(mod.compare(locked, lookalikes)) == 2


