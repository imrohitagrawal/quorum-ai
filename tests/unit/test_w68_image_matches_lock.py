def test_the_listing_snippet_prints_every_distribution_as_name_equals_version(
    capsys: pytest.CaptureFixture[str],
) -> None:
    """Red when: the ``-c`` snippet handed to the image's python does not run,
    or does not print ``name==version`` for the installed distributions.
    Checked by running the snippet with THIS interpreter: its output must
    parse to pins that include pytest at the version importlib reports, and
    must not be a handful of lines (this venv holds well over 20)."""
    mod = _module()
    fake = _FakeRun(_Done(0, _LOCKED), _Done(0, _INSTALLED_SAME))
    mod.main(["--image", "quorum-ai:test-tag"], run=fake)
    capsys.readouterr()
    argv = fake.tool_calls("docker")[0]
    snippet = argv[argv.index("-c") + 1]
    result = subprocess.run(
        [sys.executable, "-c", snippet], capture_output=True, text=True, check=False
    )
    assert result.returncode == 0, result.stderr
    pins = mod.parse_pins(result.stdout)
    assert pins.get("pytest") == importlib.metadata.version("pytest"), sorted(pins)
    assert len(pins) > 20, pins
