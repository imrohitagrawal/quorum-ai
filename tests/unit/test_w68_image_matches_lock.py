def test_parse_pins_normalizes_names_per_pep_503() -> None:
    """Red when: names are not lowercased with runs of ``-``, ``_`` and ``.``
    collapsed to one ``-``, so ``Typing_Extensions`` in the image would not
    match ``typing-extensions`` in the lock."""
    text = "Typing_Extensions==4.15.0\nzope.interface==7.2\nFoo__-.Bar==1.0\nPyYAML==6.0.3\n"
    assert _module().parse_pins(text) == {
        "typing-extensions": "4.15.0",
        "zope-interface": "7.2",
        "foo-bar": "1.0",
        "pyyaml": "6.0.3",
    }


def test_parse_pins_skips_comments_options_and_blank_lines() -> None:
    """Red when: a header comment, ``# via`` line, option line, ``-e`` line
    or blank line becomes a pin, or a real pin among them is lost."""
    text = (
        "# This file was autogenerated by uv\n"
        "--index-url https://pypi.org/simple\n"
        "-e ./\n"
        "\n"
        "anyio==4.14.0\n"
        "    # via starlette\n"
    )
    assert _module().parse_pins(text) == {"anyio": "4.14.0"}


def test_parse_pins_evaluates_markers_for_linux_cpython_312_by_default() -> None:
    """Red when: a ``win32``, ``darwin`` or older-Python marker line is kept
    for the Linux image, or a marker line that holds on Linux / CPython 3.12
    is dropped. The darwin pair is what catches evaluating markers for the
    machine running the check (a Mac) instead of the image."""
    text = (
        "colorama==0.4.6 ; sys_platform == 'win32'\n"
        "appnope==0.1.4 ; sys_platform == 'darwin'\n"
        "tomli==2.2.1 ; python_version < '3.11'\n"
        "uvloop==0.22.1 ; platform_python_implementation != 'PyPy' and "
        "sys_platform != 'cygwin' and sys_platform != 'win32'\n"
        "linux-only==1.0 ; sys_platform == 'linux'\n"
        "cffi==2.1.1 ; platform_python_implementation != 'PyPy'\n"
    )
    assert _module().parse_pins(text) == {
        "uvloop": "0.22.1",
        "linux-only": "1.0",
        "cffi": "2.1.1",
    }


def test_parse_pins_evaluates_markers_for_the_env_it_is_given() -> None:
    """Red when: the ``env`` argument is ignored, so the target environment
    cannot be changed (here Windows keeps ``colorama`` and drops the Linux
    line)."""
    windows = {
        "sys_platform": "win32",
        "platform_system": "Windows",
        "python_version": "3.12",
        "python_full_version": "3.12.13",
        "implementation_name": "cpython",
        "platform_python_implementation": "CPython",
        "os_name": "nt",
        "platform_machine": "AMD64",
    }
    text = "colorama==0.4.6 ; sys_platform == 'win32'\nlinux-only==1.0 ; sys_platform == 'linux'\n"
    assert _module().parse_pins(text, env=windows) == {"colorama": "0.4.6"}


