def test_main_version_difference_exits_1_and_prints_it(capsys: pytest.CaptureFixture[str]) -> None:
    """Red when: an image carrying urllib3 2.8.0 against a lock pinning 2.7.0
    does not exit 1, or no printed line names urllib3 with both versions."""
    installed = _INSTALLED_SAME.replace("urllib3==2.7.0", "urllib3==2.8.0")
    fake = _FakeRun(_Done(0, _LOCKED), _Done(0, installed))
    assert _module().main(["--image", "quorum-ai:test-tag"], run=fake) == 1
    _, everything = _output(capsys)
    rows = [ln for ln in everything.splitlines() if "urllib3" in ln]
    assert any("2.7.0" in ln and "2.8.0" in ln for ln in rows), everything


