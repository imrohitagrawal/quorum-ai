"""W68: ``scripts/check_image_matches_lock.py`` proves the built image holds
exactly the runtime packages ``uv.lock`` pins (finding S4 of
``docs/analysis/2026-10-13-security-review.md``: CI's docker-build log for run
38408508822 installs sentry-sdk 2.72.0, anyio 4.15.1 and urllib3 2.8.0 while
the lock pins 2.63.0, 4.14.0 and 2.7.0).

Changing the Dockerfile to ``uv sync --frozen`` fixes today's image; this
check is what keeps a later Dockerfile edit from drifting off the lock again
without anyone noticing. Subprocesses go through the injected ``run``, so no
test needs ``uv`` or Docker. One test does run the script's own distribution
listing snippet with this interpreter, to prove the snippet works.

WHAT TURNS THIS FILE RED: make ``compare`` miss a missing, extra or
different-version package, evaluate markers for the machine running the check
instead of the Linux image, or let ``main`` pass when either side is empty.
"""

from __future__ import annotations

import importlib.metadata
import importlib.util
import subprocess
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType

import pytest
from tests.repo_root import find_repo_root

_SCRIPT = find_repo_root(Path(__file__)) / "scripts" / "check_image_matches_lock.py"

_LOCKED = """\
# This file was autogenerated by uv via the following command:
#    uv export --frozen --no-dev --no-emit-project --no-hashes
anyio==4.14.0
    # via
    #   starlette
colorama==0.4.6 ; sys_platform == 'win32'
    # via
    #   click
    #   uvicorn
typing-extensions==4.15.0
    # via pydantic
urllib3==2.7.0
    # via sentry-sdk
"""

# The same three packages as the image's importlib.metadata reports them:
# names as the distributions spell them, not normalized.
_INSTALLED_SAME = "anyio==4.14.0\nTyping_Extensions==4.15.0\nurllib3==2.7.0\n"


def _module() -> ModuleType:
    assert _SCRIPT.is_file(), f"{_SCRIPT} does not exist"
    spec = importlib.util.spec_from_file_location("check_image_matches_lock_under_test", _SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@dataclass
class _Done:
    returncode: int
    stdout: str
    stderr: str = ""


class _FakeRun:
    """``uv`` gets the locked export, ``docker`` gets the installed listing."""

    def __init__(self, locked: _Done, installed: _Done) -> None:
        self.locked = locked
        self.installed = installed
        self.calls: list[list[str]] = []

    def __call__(self, command: Sequence[object], **_kwargs: object) -> _Done:
        argv = [str(a) for a in command]
        self.calls.append(argv)
        tool = Path(argv[0]).name
        if tool == "uv":
            return self.locked
        if tool == "docker":
            return self.installed
        raise AssertionError(f"unexpected command: {argv}")

    def tool_calls(self, tool: str) -> list[list[str]]:
        return [c for c in self.calls if Path(c[0]).name == tool]


def _output(capsys: pytest.CaptureFixture[str]) -> tuple[list[str], str]:
    captured = capsys.readouterr()
    return captured.out.splitlines(), captured.out + captured.err


